//! A private seed provisioned by the installer supplies entropy on kernels
//! without getrandom(2). Rotate it durably before crediting it, so a restart
//! cannot credit the same seed twice. Never credit /dev/urandom's own output
//! as new entropy without first mixing this independently generated seed.

#[cfg(target_os = "linux")]
pub fn seed() {
    if let Err(e) = seed_legacy_kernel() {
        crate::logf!("entropy: {e}");
    }
}

#[cfg(target_os = "linux")]
fn seed_legacy_kernel() -> std::io::Result<()> {
    use std::io::{Read, Write};
    use std::os::{fd::AsRawFd, unix::fs::OpenOptionsExt};
    let mut probe = [0u8; 1];
    // SAFETY: the buffer is as long as the length passed.
    let missing = unsafe { libc::syscall(libc::SYS_getrandom, probe.as_mut_ptr(), 1, libc::GRND_NONBLOCK) } < 0
        && std::io::Error::last_os_error().raw_os_error() == Some(libc::ENOSYS);
    if !missing {
        return Ok(());
    }
    let path = std::path::Path::new("/etc/nestlocal/random-seed");
    let bytes = std::fs::read(path)?;
    let buf: [u8; 64] = bytes.try_into().map_err(|_| std::io::Error::new(
        std::io::ErrorKind::InvalidData, "random-seed must contain 64 installer-generated bytes"))?;
    let mut random = std::fs::OpenOptions::new().read(true).write(true).open("/dev/urandom")?;
    random.write_all(&buf)?;
    let mut next = [0u8; 64];
    random.read_exact(&mut next)?;
    let temporary = path.with_extension("partial");
    let mut file = std::fs::OpenOptions::new().write(true).create(true).truncate(true).mode(0o600).open(&temporary)?;
    file.write_all(&next)?;
    file.sync_all()?;
    std::fs::rename(&temporary, path)?;
    std::fs::File::open(path.parent().unwrap())?.sync_all()?;

    #[repr(C)]
    struct Entropy {
        bits: libc::c_int,
        size: libc::c_int,
        buf: [u8; 64],
    }
    let entropy = Entropy { bits: 256, size: 64, buf };
    let pool = std::fs::OpenOptions::new().write(true).open("/dev/random")?;
    // _IOW('R', 3, int[2]): the count and the size, followed by the seed.
    const RNDADDENTROPY: libc::c_ulong = 0x4008_5203;
    // SAFETY: the ioctl reads the struct, whose buffer is size bytes long.
    if unsafe { libc::ioctl(pool.as_raw_fd(), RNDADDENTROPY as _, &entropy) } != 0 {
        return Err(std::io::Error::last_os_error());
    }
    crate::logf!("entropy: loaded and rotated the private installation seed");
    Ok(())
}

#[cfg(not(target_os = "linux"))]
pub fn seed() {}
